import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';
import {launchBrowser} from '../scripts/lib.mjs';

const browser=await launchBrowser();
const errors=[];
const dir='.impeccable/review';await mkdir(dir,{recursive:true});
try {
  const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
  page.on('pageerror',error=>errors.push(error.message));
  page.on('console',message=>{if(message.type()==='error')errors.push(message.text());});
  await page.goto('http://127.0.0.1:5180/',{waitUntil:'networkidle'});
  await page.waitForFunction(()=>window.ampulheta?.ready);
  await page.evaluate(()=>window.ampulheta.renderAt(0));
  await page.screenshot({path:`${dir}/desktop.png`,fullPage:true});
  const png=await page.evaluate(()=>window.ampulheta.capture());
  await writeFile(`${dir}/composition.png`,Buffer.from(png.split(',')[1],'base64'));
  await page.locator('#brightness').fill('2');await page.locator('#brightness').dispatchEvent('input');
  assert.equal(await page.evaluate(()=>window.ampulheta.getConfig().brightness),2);
  await page.getByRole('button',{name:'Restaurar'}).click();
  assert.equal(await page.evaluate(()=>window.ampulheta.getConfig().brightness),1);
  await page.getByRole('button',{name:'Comparar referência'}).click();
  await page.waitForFunction(()=>document.querySelector('video').readyState>=2);
  await page.locator('#comparison-split').fill('65');await page.locator('#comparison-split').dispatchEvent('input');
  await page.evaluate(()=>document.getElementById('notice').hidden=true);
  await page.screenshot({path:`${dir}/comparison.png`,fullPage:true});
  await page.getByRole('button',{name:'Composição',exact:true}).click();
  await page.locator('#timeline').fill('2');await page.locator('#timeline').dispatchEvent('input');
  assert.equal(await page.locator('#time-display').textContent(),'00:02.00');
  await page.getByRole('button',{name:'Reproduzir',exact:true}).click();
  await page.waitForTimeout(200);await page.getByRole('button',{name:'Pausar',exact:true}).click();
  assert(Number(await page.locator('#timeline').inputValue())>2);
  await page.getByRole('button',{name:'Voltar ao início'}).click();
  await page.getByRole('button',{name:'Modo cinema'}).click();
  assert(await page.locator('body').evaluate(el=>el.classList.contains('cinema-mode')));
  await page.keyboard.press('Escape');
  const downloadPromise=page.waitForEvent('download');await page.getByRole('button',{name:'Salvar quadro PNG'}).click();
  const download=await downloadPromise;await download.saveAs(`${dir}/downloaded.png`);
  const presetPromise=page.waitForEvent('download');await page.getByRole('button',{name:'Salvar ajustes'}).click();
  const preset=await presetPromise;await preset.saveAs(`${dir}/preset.json`);
  await page.locator('#preset-file').setInputFiles({name:'invalid.json',mimeType:'application/json',buffer:Buffer.from('bad json')});
  assert(await page.locator('#notice').isVisible());
  await page.locator('#preset-file').setInputFiles({name:'preset.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify({config:{brightness:1.2}}))});
  assert.equal(await page.evaluate(()=>window.ampulheta.getConfig().brightness),1.2);
  await page.getByRole('button',{name:'Restaurar'}).click();
  await page.evaluate(()=>document.getElementById('notice').hidden=true);
  await page.setViewportSize({width:390,height:844});await page.evaluate(()=>scrollTo(0,0));
  await page.screenshot({path:`${dir}/mobile.png`,fullPage:true});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile overflow');
  assert.deepEqual(errors,[]);
  console.log('PASS UI: sliders, reset, reference video, comparison split, timeline, playback, cinema, PNG, JSON import/export, mobile overflow, browser errors.');
}finally{await browser.close();}
